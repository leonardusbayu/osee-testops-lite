"""Generate and check exact staff SQL bindings in the owned candidate."""
import argparse
import hashlib
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'db/queries/staff_identity.sql'
TARGET = ROOT / 'db/queries/staff_identity_generated.go'


def render_bindings(module: str = "staff_identity") -> str:
    if module not in {"staff_identity", "auth", "intake", "sessions"}:
        raise ValueError("Unknown query binding module")
    source = ROOT / ("db/queries/" + module + ".sql")
    target = ROOT / ("db/queries/" + module + "_generated.go")
    spec = importlib.util.spec_from_file_location('candidate_control', ROOT / 'scripts/candidate-control.py')
    if spec is None or spec.loader is None:
        raise RuntimeError('Candidate ownership controller is unavailable')
    control = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(control)
    control._owner()
    for path in [source, target.parent]:
        control._no_reparse(path)
    if target.exists():
        control._no_reparse(target)
    raw = source.read_bytes()
    text = raw.decode('utf-8')
    header = re.compile(r'^-- name: ([A-Z][A-Za-z0-9]*) :(?:one|exec|execrows)\r?$', re.MULTILINE)
    matches = list(header.finditer(text))
    if not matches or len({match.group(1) for match in matches}) != len(matches):
        raise ValueError('Missing or duplicate staff query names')
    lines = ['// Code generated by scripts/generate-staff-queries.py; DO NOT EDIT.',
             '// Source SHA256: ' + hashlib.sha256(raw).hexdigest(), 'package queries', '']
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        statement = text[match.end():end].strip('\r\n')
        if not statement or '`' in statement or not statement.endswith(';'):
            raise ValueError('Invalid bounded staff query statement')
        lines += ['const ' + match.group(1) + ' = `', statement, '`', '']
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--module', choices=['staff_identity', 'auth', 'intake', 'sessions'], default='staff_identity')
    args = parser.parse_args()
    target = ROOT / ('db/queries/' + args.module + '_generated.go')
    expected = render_bindings(args.module)
    if args.check:
        if not target.is_file() or target.read_bytes() != expected.encode('utf-8'):
            raise ValueError('Staff SQL bindings differ from exact reviewed source')
    else:
        target.write_bytes(expected.encode('utf-8'))
    print('Exact staff SQL bindings verified' if args.check else 'Staff SQL bindings generated')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
